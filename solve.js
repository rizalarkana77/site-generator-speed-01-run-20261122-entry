// Fast drop-in for makefun-site 1.0.0 (site-generator-speed-01-run-20261122).
//
// Same answers as the reference, byte for byte, on every case — same front
// matter, template dialect, Markdown subset, slug rule and report — built
// from first principles for speed:
//
//   * Markdown is rendered in one pass over the body's lines, with no token
//     array: blocks are recognised and emitted directly, and inline markup
//     is scanned with a native regex that jumps straight to the next special
//     character instead of stepping one character at a time.
//   * HTML escaping and slugifying take a fast path (plain strings are
//     returned untouched; ASCII slugs skip Unicode normalisation) and slugs
//     are memoised within a case (titles, tags and headings repeat a lot).
//   * Templates are parsed once per case and rendered by a tight tree walk
//     that appends to an array and joins once, with cheap scope lookups.
//   * Per-page cards are built once and reused (the reference builds each
//     post's card twice); word counts scan for whitespace runs instead of
//     allocating a match array; link targets are resolved once per source.
//
// Nothing is cached from one case to the next: every cache below is created
// fresh inside run().

// ---------------------------------------------------------------- text

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
const HAS_SPECIAL = /[&<>"']/;
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** Fresh per run() call: slug text -> slug. */
let slugCache = null;

/** `text` with & < > " and ' escaped (fast path when none are present). */
function esc(text) {
  return HAS_SPECIAL.test(text) ? text.replace(/[&<>"']/g, (c) => ESCAPES[c]) : text;
}

/** One character's escape (or itself when it needs none). */
const esc1 = (c) => ESCAPES[c] ?? c;

const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/** The slug of `text`, memoised within the case. */
function slugify(text) {
  const hit = slugCache.get(text);
  if (hit !== undefined) return hit;
  // ASCII-only text needs no NFKD normalisation and has no combining marks.
  const plain = /[^\x00-\x7F]/.test(text) ? text.normalize('NFKD').replace(/\p{M}/gu, '') : text;
  let out = '';
  let gap = false;
  for (let i = 0; i < plain.length; i++) {
    const ch = plain[i];
    let keep = null;
    if (ch >= 'A' && ch <= 'Z') keep = ch.toLowerCase();
    else if ((ch >= 'a' && ch <= 'z') || (ch >= '0' && ch <= '9')) keep = ch;
    if (keep === null) {
      gap = out.length > 0;
      continue;
    }
    if (gap) out += '-';
    gap = false;
    out += keep;
  }
  let end = out.length > 64 ? 64 : out.length;
  while (end > 0 && out[end - 1] === '-') end--;
  const slug = end === 0 ? 'untitled' : out.slice(0, end);
  slugCache.set(text, slug);
  return slug;
}

/** `slug` made unique against `taken` (and added to it). */
function uniqueSlug(slug, taken) {
  let out = slug;
  for (let n = 2; taken.has(out); n++) out = `${slug}-${n}`;
  taken.add(out);
  return out;
}

/** A YYYY-MM-DD date in words, from the string alone. */
function longDate(date) {
  return `${Number(date.slice(8, 10))} ${MONTHS[Number(date.slice(5, 7)) - 1]} ${date.slice(0, 4)}`;
}

/** Whether code unit `c` is a JS \s whitespace character. */
function isWSCode(c) {
  return c === 32 || (c >= 9 && c <= 13) || c === 160 || c === 0x1680 || (c >= 0x2000 && c <= 0x200a) ||
    c === 0x2028 || c === 0x2029 || c === 0x202f || c === 0x205f || c === 0x3000 || c === 0xfeff;
}

/** The words of a body: its runs of characters other than whitespace. */
function wordsOf(text) {
  let n = 0;
  let inWord = false;
  for (let i = 0; i < text.length; i++) {
    if (isWSCode(text.charCodeAt(i))) inWord = false;
    else if (!inWord) { inWord = true; n++; }
  }
  return n;
}

// ---------------------------------------------------------------- front matter

const KEYS = new Set(['title', 'date', 'tags', 'draft', 'layout', 'slug', 'summary']);

function daysIn(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28;
  return m === 4 || m === 6 || m === 9 || m === 11 ? 30 : 31;
}

/** A string value: "..." with \" and \\ its only escapes, or bare. */
function stringOf(raw) {
  if (raw[0] === '"') {
    if (raw.length < 2 || raw[raw.length - 1] !== '"') return { error: 'a quoted string is not closed' };
    let out = '';
    for (let i = 1; i < raw.length - 1; i++) {
      const c = raw[i];
      if (c === '\\') {
        const n = raw[i + 1];
        if ((n !== '"' && n !== '\\') || i + 1 === raw.length - 1) return { error: 'a quoted string holds an escape other than \\" or \\\\' };
        out += n;
        i++;
      } else if (c === '"') return { error: 'a quoted string holds a stray quote' };
      else out += c;
    }
    return { value: out };
  }
  if (raw[0] === '[') return { error: 'a bare string opens on [' };
  return { value: raw };
}

/** One key's value, or why it is refused. */
function valueOf(key, raw) {
  switch (key) {
    case 'title':
    case 'summary': {
      const s = stringOf(raw);
      return 'error' in s ? { error: `key "${key}": ${s.error}` } : s;
    }
    case 'date': {
      let y = 0, mo = 0, d = 0;
      let ok = raw.length === 10 && raw[4] === '-' && raw[7] === '-';
      if (ok) {
        for (let i = 0; i < 10 && ok; i++) {
          if (i === 4 || i === 7) continue;
          const c = raw.charCodeAt(i);
          if (c < 48 || c > 57) ok = false;
        }
      }
      if (ok) {
        y = Number(raw.slice(0, 4)); mo = Number(raw.slice(5, 7)); d = Number(raw.slice(8, 10));
        if (y < 1970 || y > 2099 || mo < 1 || mo > 12 || d < 1 || d > daysIn(y, mo)) ok = false;
      }
      if (!ok) return { error: 'key "date": not a date from 1970-01-01 to 2099-12-31 (YYYY-MM-DD)' };
      return { value: raw };
    }
    case 'tags': {
      if (raw[0] !== '[' || raw[raw.length - 1] !== ']') return { error: 'key "tags": not a list [a, b]' };
      const inner = raw.slice(1, -1);
      if (inner.trim() === '') return { value: [] };
      const tags = inner.split(',');
      for (let i = 0; i < tags.length; i++) {
        tags[i] = tags[i].trim();
        const t = tags[i];
        if (t === '' || t.indexOf('"') !== -1 || t.indexOf('[') !== -1 || t.indexOf(']') !== -1) {
          return { error: 'key "tags": an empty tag, or one holding " [ or ]' };
        }
      }
      return { value: tags };
    }
    case 'draft':
      return raw === 'true' ? { value: true } : raw === 'false' ? { value: false } : { error: 'key "draft": true or false' };
    case 'layout': {
      let ok = raw.length > 0;
      for (let i = 0; i < raw.length && ok; i++) {
        const c = raw[i];
        if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '-')) ok = false;
      }
      return ok ? { value: raw } : { error: 'key "layout": not a template name' };
    }
    case 'slug': {
      let ok = raw.length > 0 && raw.length <= 64;
      let prevDash = true; // a slug may not start with '-'
      for (let i = 0; i < raw.length && ok; i++) {
        const c = raw[i];
        if (c === '-') {
          if (prevDash) ok = false;
          prevDash = true;
        } else if ((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9')) prevDash = false;
        else ok = false;
      }
      if (prevDash) ok = false; // may not end with '-'
      return ok ? { value: raw } : { error: 'key "slug": not a slug' };
    }
    default:
      return { error: `unknown key "${key}"` };
  }
}

/** Whether `line` is blank (spaces and tabs only). */
function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

/** `line` with spaces and tabs stripped at both ends. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line[a] === ' ' || line[a] === '\t')) a++;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  return line.slice(a, b);
}

/**
 * A source's front matter and body: { data, body }, or { error } with the
 * first reason it is refused. `text` has "\n" line ends.
 */
function parseFrontMatter(text) {
  let nl = text.indexOf('\n');
  if ((nl === -1 ? text : text.slice(0, nl)) !== '---') return { error: 'no front matter' };
  // Find the closing '---' line; `closeEnd` is the position just after it.
  let i = nl === -1 ? text.length : nl + 1;
  let closeLine = -1;
  let closeEnd = -1;
  let lineNo = 1;
  while (i <= text.length) {
    const e = text.indexOf('\n', i);
    const line = e === -1 ? text.slice(i) : text.slice(i, e);
    if (line === '---') { closeLine = lineNo; closeEnd = e === -1 ? text.length : e + 1; break; }
    if (e === -1) break;
    i = e + 1;
    lineNo++;
  }
  if (closeLine === -1) return { error: 'the front matter is not closed' };
  const data = {};
  let hasTitle = false;
  // Re-walk the lines between the opening and closing '---'.
  i = nl === -1 ? text.length : nl + 1;
  for (let ln = 1; ln < closeLine; ln++) {
    const e = text.indexOf('\n', i);
    const line = e === -1 ? text.slice(i) : text.slice(i, e);
    i = e === -1 ? text.length : e + 1;
    if (isBlank(line) || line[0] === '#') continue;
    // key: [a-z_]+, ':', then one space and the value (or nothing).
    let j = 0;
    while (j < line.length && ((line[j] >= 'a' && line[j] <= 'z') || line[j] === '_')) j++;
    if (j === 0 || line[j] !== ':') return { error: `line ${ln + 1} is not "key: value"` };
    const key = line.slice(0, j);
    j++;
    let raw;
    if (j === line.length) raw = '';
    else if (line[j] === ' ') raw = line.slice(j + 1).replace(/[ \t]+$/, '');
    else return { error: `line ${ln + 1} is not "key: value"` };
    if (!KEYS.has(key)) return { error: `unknown key "${key}"` };
    if (Object.hasOwn(data, key)) return { error: `key "${key}" is given twice` };
    if (raw === '') return { error: `key "${key}" has no value` };
    const v = valueOf(key, raw);
    if ('error' in v) return v;
    data[key] = v.value;
    if (key === 'title') hasTitle = true;
  }
  if (!hasTitle) return { error: 'no title' };
  return { data, body: text.slice(closeEnd) };
}

